const UI_LANG_KEY = "mtg-proxy-ui-lang";
let uiLang = "en";

const uiLangEntry = (code) => UI_LANGS.find((l) => l.code === code) || UI_LANGS[0];

// Only substitutes placeholders that were actually passed, so rules-text
// braces in the strings themselves ({T}, {2}, {W}…) are left alone.
function t(key, params = {}) {
  const raw = STRINGS[uiLang]?.[key] ?? STRINGS.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (m, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? params[name] : m);
}

// Plural form of a counted noun: `base` is a key prefix whose variants are
// named after the CLDR categories ("grid.card.one", ".few", ".many",
// ".other"). Intl.PluralRules picks the category for the locale, and any
// category a language does not spell out falls back to ".other".
const pluralRules = new Map();
function plural(base, n) {
  const tag = uiLangEntry(uiLang).tag;
  if (!pluralRules.has(tag)) pluralRules.set(tag, new Intl.PluralRules(tag));
  const key = `${base}.${pluralRules.get(tag).select(n)}`;
  const known = (k) => (STRINGS[uiLang]?.[k] ?? STRINGS.en[k]) !== undefined;
  return t(known(key) ? key : `${base}.other`);
}

// Browser preference → one of our locales ("zh-TW" → zht, "pt-BR" → pt…).
function detectUiLang() {
  for (const pref of navigator.languages || [navigator.language || ""]) {
    const low = pref.toLowerCase();
    if (low.startsWith("zh")) {
      return /hant|tw|hk|mo/.test(low) ? "zht" : "zhs";
    }
    const base = low.split("-")[0];
    if (UI_LANGS.some((l) => l.code === base)) return base;
  }
  return "en";
}

// Translate everything carrying a data-i18n* attribute.
function applyI18n() {
  const globals = { scryfall: LINK_SCRYFALL };
  for (const el of document.querySelectorAll("[data-i18n]")) {
    let text = t(el.dataset.i18n, globals);
    // Translator options: "<name> [speed ★☆☆ / quality ★★★]"
    if (el.dataset.stars) {
      const [s, q] = el.dataset.stars.split("|");
      text += " " + t("ctrl.ratings", { s, q });
    }
    el.textContent = text;
  }
  for (const el of document.querySelectorAll("[data-i18n-html]")) {
    el.innerHTML = t(el.dataset.i18nHtml, globals);
  }
  for (const el of document.querySelectorAll("[data-i18n-title]")) {
    el.title = t(el.dataset.i18nTitle, globals);
  }
  for (const el of document.querySelectorAll("[data-i18n-placeholder]")) {
    el.placeholder = t(el.dataset.i18nPlaceholder, globals);
  }
}

// Switch the interface language: persist it, retranslate the static markup
// and let app.js repaint whatever it rendered itself (grid, badges…).
function setUiLang(code, { persist = true } = {}) {
  const entry = uiLangEntry(code);
  uiLang = entry.code;
  document.documentElement.lang = entry.tag;
  if (persist) {
    try { localStorage.setItem(UI_LANG_KEY, uiLang); } catch { /* private mode */ }
  }
  const flag = document.getElementById("ui-lang-flag");
  const short = document.getElementById("ui-lang-short");
  if (flag) flag.textContent = entry.flag;
  if (short) short.textContent = entry.short;
  for (const li of document.querySelectorAll("#ui-lang-menu li")) {
    li.classList.toggle("current", li.dataset.lang === uiLang);
  }
  applyI18n();
  document.dispatchEvent(new CustomEvent("uilangchange", { detail: uiLang }));
}

// Flag picker sitting next to the GitHub buttons.
function buildLangPicker() {
  const menu = document.getElementById("ui-lang-menu");
  const btn = document.getElementById("ui-lang-btn");
  if (!menu || !btn) return;

  for (const l of UI_LANGS) {
    const li = document.createElement("li");
    li.dataset.lang = l.code;
    li.innerHTML = `<span class="flag"></span><span class="name"></span>`;
    li.querySelector(".flag").textContent = l.flag;
    li.querySelector(".name").textContent = l.name;
    li.addEventListener("click", () => {
      setUiLang(l.code);
      menu.classList.add("hidden");
    });
    menu.appendChild(li);
  }

  const close = () => menu.classList.add("hidden");
  btn.addEventListener("click", (e) => {
    e.stopPropagation();
    menu.classList.toggle("hidden");
  });
  btn.addEventListener("keydown", (e) => {
    if (e.key === "Enter" || e.key === " ") { e.preventDefault(); btn.click(); }
  });
  document.addEventListener("click", close);
  document.addEventListener("keydown", (e) => { if (e.key === "Escape") close(); });
}

